-- Read-only, run by the agent just after the main crawler restarted on 1.1.0 (2026-10-15):
-- is the production crawl writing CONTENT_MD, links and references, and is any page on the legacy fallback?

-- 1. Sections written in the last 20 minutes, by family: with and without CONTENT_MD.
SELECT ITEM_TYPE, COUNT(DISTINCT ID_WIKIDATA, LANG) AS PAGES, COUNT(*) AS SECTIONS,
  SUM(CONTENT_MD IS NOT NULL) AS WITH_MD, SUM(CONTENT_MD IS NULL) AS WITHOUT_MD, MIN(TIM_UPDATED) AS FIRST_WRITE, MAX(TIM_UPDATED) AS LAST_WRITE
FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION
WHERE TIM_UPDATED >= NOW() - INTERVAL 20 MINUTE
GROUP BY ITEM_TYPE;

-- 2. Pages written in the last 20 minutes with at least one section lacking CONTENT_MD (legacy fallback or older build).
SELECT ID_WIKIDATA, LANG, ITEM_TYPE, COUNT(*) AS SECTIONS_WITHOUT_MD, MAX(TIM_UPDATED) AS LAST_WRITE
FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION
WHERE TIM_UPDATED >= NOW() - INTERVAL 20 MINUTE AND CONTENT_MD IS NULL
GROUP BY ID_WIKIDATA, LANG, ITEM_TYPE
LIMIT 20;

-- 3. Links and references written in the last 20 minutes.
SELECT 'links' AS KIND, COUNT(DISTINCT ID_WIKIDATA, LANG) AS PAGES, COUNT(*) AS ROWS_WRITTEN,
  SUM(IS_DATE) AS DATES, SUM(IS_REDLINK) AS REDLINKS, SUM(RESOLVED_BY = 'title') AS BY_TITLE,
  SUM(RESOLVED_BY = 'api') AS BY_API, SUM(IS_REDLINK = 0 AND IS_DATE = 0 AND TARGET_ID_WIKIDATA IS NULL) AS LIVE_WITHOUT_QID
FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK WHERE TIM_UPDATED >= NOW() - INTERVAL 20 MINUTE
UNION ALL
SELECT 'references', COUNT(DISTINCT ID_WIKIDATA, LANG), COUNT(*), NULL, NULL, NULL, NULL, SUM(REFERENCE_TEXT IS NULL)
FROM T_WC_WIKIPEDIA_PAGE_LANG_REFERENCE WHERE TIM_UPDATED >= NOW() - INTERVAL 20 MINUTE;

-- 4. Pages crawled successfully in the last 20 minutes (the crawler's own ledger), for the rate.
SELECT ITEM_TYPE, COUNT(*) AS PAGES, MIN(LAST_SUCCESS_AT) AS FIRST_SUCCESS, MAX(LAST_SUCCESS_AT) AS LAST_SUCCESS
FROM T_WC_WIKIPEDIA_PAGE_LANG
WHERE LAST_SUCCESS_AT >= NOW() - INTERVAL 20 MINUTE
GROUP BY ITEM_TYPE;
