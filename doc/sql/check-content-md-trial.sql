-- Read-only, run by the agent before and after the 1.1.0 trial (wikipedia-crawler-manual.sh on 14 Qids):
-- per page, the family it is stored under (the strcontent to pass), its sections, and what 1.1.0 wrote.
-- Pages: the 2026-10-15 prototype set, eleven kinds of entities, en and fr.

CREATE TEMPORARY TABLE TMP_TRIAL (ID_WIKIDATA varchar(50) PRIMARY KEY) DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
INSERT INTO TMP_TRIAL VALUES ('Q2085'), ('Q164562'), ('Q370180'), ('Q72594'), ('Q102427'), ('Q192017'), ('Q185867'),
  ('Q1433745'), ('Q27877321'), ('Q2543252'), ('Q41483'), ('Q69126055'), ('Q1544011'), ('Q8275');

-- 1. Pages, family and crawl dates.
SELECT p.ID_WIKIDATA, p.LANG, p.ITEM_TYPE, p.PAGE_EXISTS, LEFT(p.WIKIPEDIA_PAGE_TITLE, 45) AS PAGE_TITLE,
  p.LAST_SUCCESS_AT
FROM T_WC_WIKIPEDIA_PAGE_LANG p INNER JOIN TMP_TRIAL t ON t.ID_WIKIDATA = p.ID_WIKIDATA
ORDER BY p.ID_WIKIDATA, p.LANG;

-- 2. Sections: count, how many carry CONTENT_MD, sizes, last write.
SELECT s.ID_WIKIDATA, s.LANG, COUNT(*) AS SECTIONS, SUM(s.CONTENT_MD IS NOT NULL) AS WITH_MD,
  SUM(CHAR_LENGTH(s.CONTENT)) AS CHARS_TEXT, SUM(CHAR_LENGTH(s.CONTENT_MD)) AS CHARS_MD, MAX(s.TIM_UPDATED) AS LAST_WRITE
FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION s INNER JOIN TMP_TRIAL t ON t.ID_WIKIDATA = s.ID_WIKIDATA
GROUP BY s.ID_WIKIDATA, s.LANG ORDER BY s.ID_WIKIDATA, s.LANG;

-- 3. Links: totals, flags, how they were resolved.
SELECT l.ID_WIKIDATA, l.LANG, COUNT(*) AS LINKS, SUM(l.IS_DATE) AS DATES, SUM(l.IS_REDLINK) AS REDLINKS,
  SUM(l.RESOLVED_BY = 'title') AS BY_TITLE, SUM(l.RESOLVED_BY = 'api') AS BY_API,
  SUM(l.TARGET_ID_WIKIDATA IS NOT NULL) AS WITH_QID, SUM(l.VIA_REDIRECT) AS VIA_REDIRECT,
  SUM(l.SECTION_DISPLAY_ORDER > (SELECT MAX(s.DISPLAY_ORDER) FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION s
    WHERE s.ID_WIKIDATA = l.ID_WIKIDATA AND s.LANG = l.LANG)) AS ORPHAN_SECTION
FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK l INNER JOIN TMP_TRIAL t ON t.ID_WIKIDATA = l.ID_WIKIDATA
GROUP BY l.ID_WIKIDATA, l.LANG ORDER BY l.ID_WIKIDATA, l.LANG;

-- 4. References: totals, with a URL, with text.
SELECT r.ID_WIKIDATA, r.LANG, COUNT(*) AS REFS, SUM(r.URL IS NOT NULL) AS WITH_URL,
  SUM(r.REFERENCE_TEXT IS NOT NULL) AS WITH_TEXT
FROM T_WC_WIKIPEDIA_PAGE_LANG_REFERENCE r INNER JOIN TMP_TRIAL t ON t.ID_WIKIDATA = r.ID_WIKIDATA
GROUP BY r.ID_WIKIDATA, r.LANG ORDER BY r.ID_WIKIDATA, r.LANG;

-- 5. Title join sanity: links the local join resolved whose Qid has no page under that exact title.
SELECT l.ID_WIKIDATA, l.LANG, l.TARGET_TITLE, l.TARGET_ID_WIKIDATA
FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK l INNER JOIN TMP_TRIAL t ON t.ID_WIKIDATA = l.ID_WIKIDATA
WHERE l.RESOLVED_BY = 'title' AND NOT EXISTS (SELECT 1 FROM T_WC_WIKIPEDIA_PAGE_LANG p
  WHERE p.ID_WIKIDATA = l.TARGET_ID_WIKIDATA AND p.LANG = l.LANG AND BINARY p.WIKIPEDIA_PAGE_TITLE = BINARY l.TARGET_TITLE)
LIMIT 20;

-- 6. Le Bon, la Brute et le Truand: the Format line the writer extracts from the repaired text.
SELECT ID_MOVIE, WIKIPEDIA_FORMAT_LINE, DAT_WIKIPEDIA_FORMAT_LINE FROM T_WC_TMDB_MOVIE WHERE ID_WIKIDATA = 'Q41483';
