-- Read-only, run by the agent after the 1.1.0 restart (2026-10-15). TIM_UPDATED is Paris time while the
-- server's NOW() is UTC, so the window is taken from the latest section write, not from NOW().
-- Per minute over the last 15 minutes of writes: pages, sections with and without CONTENT_MD.
SELECT DATE_FORMAT(s.TIM_UPDATED, '%Y-%m-%d %H:%i') AS MINUTE_PARIS, COUNT(DISTINCT s.ID_WIKIDATA, s.LANG) AS PAGES,
  SUM(s.CONTENT_MD IS NOT NULL) AS WITH_MD, SUM(s.CONTENT_MD IS NULL) AS WITHOUT_MD
FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION s
WHERE s.TIM_UPDATED >= (SELECT MAX(TIM_UPDATED) FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION) - INTERVAL 15 MINUTE
GROUP BY MINUTE_PARIS ORDER BY MINUTE_PARIS;

SELECT DATE_FORMAT(TIM_UPDATED, '%Y-%m-%d %H:%i') AS MINUTE_PARIS, COUNT(DISTINCT ID_WIKIDATA, LANG) AS PAGES, COUNT(*) AS LINKS,
  SUM(RESOLVED_BY = 'title') AS BY_TITLE, SUM(RESOLVED_BY = 'api') AS BY_API,
  SUM(IS_REDLINK = 0 AND IS_DATE = 0 AND TARGET_ID_WIKIDATA IS NULL) AS LIVE_WITHOUT_QID
FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK
WHERE TIM_UPDATED >= (SELECT MAX(TIM_UPDATED) FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION) - INTERVAL 15 MINUTE
GROUP BY MINUTE_PARIS ORDER BY MINUTE_PARIS;
