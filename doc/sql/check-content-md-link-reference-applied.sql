-- Read-only check, run by the agent after Philippe ran alter-content-md-link-reference.sql:
-- the CONTENT_MD column, the two new tables, the title index, and whether the column add was instant.

SELECT COLUMN_NAME, ORDINAL_POSITION, COLUMN_TYPE, CHARACTER_SET_NAME, COLLATION_NAME, IS_NULLABLE, COLUMN_DEFAULT
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'T_WC_WIKIPEDIA_PAGE_LANG_SECTION' AND COLUMN_NAME IN ('CONTENT', 'CONTENT_MD');

SELECT TABLE_NAME, ENGINE, TABLE_COLLATION, TABLE_ROWS, CREATE_TIME
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME IN ('T_WC_WIKIPEDIA_PAGE_LANG_SECTION', 'T_WC_WIKIPEDIA_PAGE_LANG_LINK', 'T_WC_WIKIPEDIA_PAGE_LANG_REFERENCE');

SELECT INDEX_NAME, SEQ_IN_INDEX, COLUMN_NAME
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'T_WC_WIKIPEDIA_PAGE_LANG' AND INDEX_NAME = 'LANG_WIKIPEDIA_PAGE_TITLE'
ORDER BY SEQ_IN_INDEX;

-- An instant add leaves the section table's CREATE_TIME unchanged (a COPY rebuild would reset it);
-- the newest section rows show the crawler kept writing.
SELECT MAX(TIM_UPDATED) AS LAST_SECTION_WRITE, SUM(CONTENT_MD IS NOT NULL) AS CONTENT_MD_FILLED
FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION
WHERE TIM_UPDATED >= NOW() - INTERVAL 1 HOUR;

SHOW CREATE TABLE T_WC_WIKIPEDIA_PAGE_LANG_LINK;
SHOW CREATE TABLE T_WC_WIKIPEDIA_PAGE_LANG_REFERENCE;
