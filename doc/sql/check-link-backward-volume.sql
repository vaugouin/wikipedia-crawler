-- Read-only, run by the agent: how heavy the "mentioned in" (backward) lookup on
-- T_WC_WIKIPEDIA_PAGE_LANG_LINK is, before tmdb-front, fastapi-text2sql and voice-agent read it.
-- Table size, links pointing to a few much-cited entities (Clint Eastwood, Sergio Leone,
-- France, United States, Paris), how many of the pages behind them are a T2S person, movie or
-- series, and the plan of the lookup on the current index (TARGET_ID_WIKIDATA alone).

SELECT TABLE_NAME, TABLE_ROWS, ROUND(DATA_LENGTH / 1048576) AS DATA_MB, ROUND(INDEX_LENGTH / 1048576) AS INDEX_MB
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME IN ('T_WC_WIKIPEDIA_PAGE_LANG_LINK', 'T_WC_WIKIPEDIA_PAGE_LANG_REFERENCE');

SELECT l.TARGET_ID_WIKIDATA, l.LANG, COUNT(*) AS LINKS, COUNT(DISTINCT l.ID_WIKIDATA) AS SOURCE_PAGES
FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK l
WHERE l.TARGET_ID_WIKIDATA IN ('Q43203', 'Q164562', 'Q142', 'Q30', 'Q90')
GROUP BY l.TARGET_ID_WIKIDATA, l.LANG ORDER BY l.TARGET_ID_WIKIDATA, l.LANG;

SELECT x.TARGET_ID_WIKIDATA, x.LANG, SUM(p.ID_PERSON IS NOT NULL) AS PERSONS, SUM(m.ID_MOVIE IS NOT NULL) AS MOVIES,
  SUM(s.ID_SERIE IS NOT NULL) AS SERIES
FROM (SELECT DISTINCT TARGET_ID_WIKIDATA, LANG, ID_WIKIDATA FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK
  WHERE TARGET_ID_WIKIDATA IN ('Q43203', 'Q164562', 'Q142', 'Q30', 'Q90')) x
LEFT JOIN T_WC_T2S_PERSON p ON p.ID_WIKIDATA = x.ID_WIKIDATA
LEFT JOIN T_WC_T2S_MOVIE m ON m.ID_WIKIDATA = x.ID_WIKIDATA
LEFT JOIN T_WC_T2S_SERIE s ON s.ID_WIKIDATA = x.ID_WIKIDATA
GROUP BY x.TARGET_ID_WIKIDATA, x.LANG ORDER BY x.TARGET_ID_WIKIDATA, x.LANG;

EXPLAIN SELECT DISTINCT ID_WIKIDATA FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK WHERE TARGET_ID_WIKIDATA = 'Q30' AND LANG = 'en';

-- Pages crawled with CONTENT_MD so far, per language: how far the backfill is.
SELECT LANG, COUNT(DISTINCT ID_WIKIDATA) AS PAGES_WITH_LINKS FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK GROUP BY LANG;
