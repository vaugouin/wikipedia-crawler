-- Before compressing T_WC_WIKIPEDIA_PAGE_LANG_SECTION.CONTENT (topic wikipedia-rich-sections):
-- can this server do it, and the baseline to compare after.
-- Read-only on the real table; the round-trip test runs on a temporary table.

-- 1. The live column definition, which the ALTER must keep (type, charset, collation, default).
SELECT COLUMN_NAME, COLUMN_TYPE, CHARACTER_SET_NAME, COLLATION_NAME, IS_NULLABLE, COLUMN_DEFAULT
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'T_WC_WIKIPEDIA_PAGE_LANG_SECTION' AND COLUMN_NAME = 'CONTENT';

SELECT TABLE_COLLATION FROM information_schema.TABLES
WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'T_WC_WIKIPEDIA_PAGE_LANG_SECTION';

-- 2. Round trip: the same column definition with COMPRESSED, 2,000 real sections copied in,
--    then compared byte for byte with the source.
CREATE TEMPORARY TABLE TMP_COMPRESS_TEST (
  ID_ROW int NOT NULL PRIMARY KEY,
  CONTENT mediumtext COMPRESSED CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci DEFAULT NULL
) ENGINE=InnoDB;

INSERT INTO TMP_COMPRESS_TEST (ID_ROW, CONTENT)
SELECT ID_ROW, CONTENT FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION ORDER BY ID_ROW DESC LIMIT 2000;

SELECT COUNT(*) AS ROWS_TESTED,
  SUM(NOT (t.CONTENT <=> s.CONTENT)) AS COLLATION_MISMATCHES,
  SUM(NOT (BINARY t.CONTENT <=> BINARY s.CONTENT)) AS BYTE_MISMATCHES,
  SUM(LENGTH(s.CONTENT)) AS RAW_BYTES
FROM TMP_COMPRESS_TEST t JOIN T_WC_WIKIPEDIA_PAGE_LANG_SECTION s ON s.ID_ROW = t.ID_ROW;

SHOW CREATE TABLE TMP_COMPRESS_TEST;
DROP TEMPORARY TABLE TMP_COMPRESS_TEST;

-- 3. Baseline footprint, to compare after the ALTER.
SELECT TABLE_ROWS, ROUND(DATA_LENGTH / 1048576) AS DATA_MB, ROUND(INDEX_LENGTH / 1048576) AS INDEX_MB,
  ROUND(DATA_FREE / 1048576) AS FREE_MB
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = 'T_WC_WIKIPEDIA_PAGE_LANG_SECTION';
