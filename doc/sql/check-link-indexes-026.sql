-- WIKIPEDIA-CRAWLER-026, point 3: the indexes of T_WC_WIKIPEDIA_PAGE_LANG_LINK as they
-- stand, to know whether alter-link-drop-unused-indexes-026.sql has run, and the sizes
-- before alter-link-primary-key-026.sql. Read-only (voie 1).

SELECT INDEX_NAME, NON_UNIQUE,
       GROUP_CONCAT(COLUMN_NAME ORDER BY SEQ_IN_INDEX) AS COLUMNS_
FROM information_schema.STATISTICS
WHERE TABLE_SCHEMA = 'vaugouindb' AND TABLE_NAME = 'T_WC_WIKIPEDIA_PAGE_LANG_LINK'
GROUP BY INDEX_NAME, NON_UNIQUE
ORDER BY INDEX_NAME;

SELECT TABLE_NAME, TABLE_ROWS,
       ROUND(DATA_LENGTH / POW(1024, 3), 1) AS DATA_GB,
       ROUND(INDEX_LENGTH / POW(1024, 3), 1) AS INDEX_GB,
       ROUND(DATA_FREE / POW(1024, 3), 1) AS FREE_GB
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = 'vaugouindb'
  AND TABLE_NAME IN ('T_WC_WIKIPEDIA_PAGE_LANG_LINK', 'T_WC_WIKIPEDIA_PAGE_LANG_REFERENCE');

SELECT ROUND(SUM(DATA_LENGTH + INDEX_LENGTH) / POW(1024, 3), 1) AS DATABASE_GB,
       ROUND(SUM(DATA_FREE) / POW(1024, 3), 1) AS DATABASE_FREE_GB
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = 'vaugouindb';
