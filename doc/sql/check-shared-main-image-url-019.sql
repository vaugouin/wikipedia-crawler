-- Lists the MAIN_IMAGE_URL values shared by 25+ distinct entities, with their entity types.
SELECT COUNT(DISTINCT ID_WIKIDATA) AS ENTITY_COUNT, GROUP_CONCAT(DISTINCT CONCAT(LANG, ':', ITEM_TYPE)) AS LANG_TYPES, MAIN_IMAGE_URL
FROM T_WC_WIKIPEDIA_PAGE_LANG
WHERE MAIN_IMAGE_URL IS NOT NULL AND MAIN_IMAGE_URL <> ''
GROUP BY MAIN_IMAGE_URL
HAVING ENTITY_COUNT >= 25
ORDER BY ENTITY_COUNT DESC;
