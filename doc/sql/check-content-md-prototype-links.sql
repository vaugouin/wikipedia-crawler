-- Title hits in one scan of PAGE_LANG (WIKIPEDIA_PAGE_TITLE has no index): drive from PAGE_LANG, look up the small keyed table.
CREATE TEMPORARY TABLE TMP_PROTO_TITLE_HIT AS
SELECT STRAIGHT_JOIN DISTINCT t.LANG, t.TARGET, p.ID_WIKIDATA
FROM T_WC_WIKIPEDIA_PAGE_LANG p
INNER JOIN TMP_PROTO_LINK t ON t.LANG = p.LANG AND t.TARGET = p.WIKIPEDIA_PAGE_TITLE;

SELECT l.PAGE,
  COUNT(*) AS LINKS,
  COUNT(DISTINCT l.QID) AS DISTINCT_QIDS,
  COUNT(DISTINCT CASE WHEN EXISTS (SELECT 1 FROM T_WC_WIKIPEDIA_PAGE_LANG p WHERE p.ID_WIKIDATA = l.QID) THEN l.QID END) AS QIDS_WE_CRAWL,
  COUNT(DISTINCT CASE WHEN EXISTS (SELECT 1 FROM T_WC_T2S_MOVIE m WHERE m.ID_WIKIDATA = l.QID) THEN l.QID END) AS QIDS_T2S_MOVIE,
  COUNT(DISTINCT CASE WHEN EXISTS (SELECT 1 FROM T_WC_T2S_PERSON m WHERE m.ID_WIKIDATA = l.QID) THEN l.QID END) AS QIDS_T2S_PERSON,
  COUNT(h.TARGET) AS LINKS_RESOLVED_BY_LOCAL_TITLE,
  SUM(h.ID_WIKIDATA IS NOT NULL AND h.ID_WIKIDATA <> l.QID) AS LOCAL_TITLE_WRONG_QID
FROM TMP_PROTO_LINK l
LEFT JOIN TMP_PROTO_TITLE_HIT h ON h.LANG = l.LANG AND h.TARGET = l.TARGET
GROUP BY l.PAGE;
