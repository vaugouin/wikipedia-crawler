-- WIKIPEDIA-CRAWLER-019: where does the "Portail:Années 1960" photo (Apollo_11_Crew.jpg) still live?
-- Read-only. Counts every column that can hold a main image, then lists the two Leone trilogies.

SELECT 'PAGE_LANG.MAIN_IMAGE_URL' AS SRC, LANG, ITEM_TYPE, COUNT(*) AS N
FROM T_WC_WIKIPEDIA_PAGE_LANG WHERE MAIN_IMAGE_URL LIKE '%Apollo_11_Crew%' GROUP BY LANG, ITEM_TYPE;

SELECT 'PAGE_LANG_IMAGE' AS SRC, LANG, ITEM_TYPE, IS_MAIN_IMAGE, COUNT(*) AS N
FROM T_WC_WIKIPEDIA_PAGE_LANG_IMAGE WHERE IMAGE_URL LIKE '%Apollo_11_Crew%' GROUP BY LANG, ITEM_TYPE, IS_MAIN_IMAGE;

SELECT 'T2S_COLLECTION' AS SRC,
  SUM(WIKIPEDIA_IMAGE_PATH LIKE '%Apollo_11_Crew%') AS IMAGE_PATH,
  SUM(WIKIPEDIA_MAIN_IMAGE_URL LIKE '%Apollo_11_Crew%') AS MAIN_EN,
  SUM(WIKIPEDIA_MAIN_IMAGE_URL_FR LIKE '%Apollo_11_Crew%') AS MAIN_FR
FROM T_WC_T2S_COLLECTION;

SELECT 'T2S_ITEM' AS SRC,
  SUM(WIKIPEDIA_IMAGE_PATH LIKE '%Apollo_11_Crew%') AS IMAGE_PATH,
  SUM(WIKIPEDIA_MAIN_IMAGE_URL LIKE '%Apollo_11_Crew%') AS MAIN_EN,
  SUM(WIKIPEDIA_MAIN_IMAGE_URL_FR LIKE '%Apollo_11_Crew%') AS MAIN_FR
FROM T_WC_T2S_ITEM;

SELECT 'T2S_MOVIE' AS SRC,
  SUM(WIKIPEDIA_MAIN_IMAGE_URL LIKE '%Apollo_11_Crew%') AS MAIN_EN,
  SUM(WIKIPEDIA_MAIN_IMAGE_URL_FR LIKE '%Apollo_11_Crew%') AS MAIN_FR
FROM T_WC_T2S_MOVIE;

SELECT 'V1_ITEM' AS SRC, COUNT(*) AS N FROM T_WC_WIKIDATA_ITEM_V1 WHERE WIKIPEDIA_IMAGE_PATH LIKE '%Apollo_11_Crew%';
SELECT 'V1_MOVIE' AS SRC, COUNT(*) AS N FROM T_WC_WIKIDATA_MOVIE_V1 WHERE WIKIPEDIA_POSTER_PATH LIKE '%Apollo_11_Crew%';

-- The two reference trilogies of the ticket (Dollars Trilogy, Once Upon a Time trilogy)
SELECT p.ID_WIKIDATA, p.LANG, p.WIKIPEDIA_PAGE_TITLE, p.MAIN_IMAGE_URL, p.LAST_SUCCESS_AT
FROM T_WC_WIKIPEDIA_PAGE_LANG p WHERE p.ID_WIKIDATA IN ('Q370180', 'Q468018');

SELECT i.ID_WIKIDATA, i.LANG, i.DISPLAY_ORDER, i.IS_MAIN_IMAGE, i.FILE_NAME
FROM T_WC_WIKIPEDIA_PAGE_LANG_IMAGE i WHERE i.ID_WIKIDATA IN ('Q370180', 'Q468018') ORDER BY i.ID_WIKIDATA, i.LANG, i.DISPLAY_ORDER;

SELECT c.* FROM T_WC_T2S_COLLECTION c WHERE c.ID_WIKIDATA IN ('Q370180', 'Q468018')\;
