-- Why was ADD COLUMN ... COMPRESSED refused as INSTANT in the dry run: the temporary table, or the
-- COMPRESSED attribute? Same test with a plain column, and with INPLACE. Read-only (temporary tables).
CREATE TEMPORARY TABLE TMP_DRY_A LIKE T_WC_WIKIPEDIA_PAGE_LANG_SECTION;
ALTER TABLE TMP_DRY_A ADD COLUMN X_PLAIN mediumtext DEFAULT NULL, ALGORITHM=INSTANT;
SELECT 'plain mediumtext INSTANT on a temporary table: done' AS STEP;

CREATE TEMPORARY TABLE TMP_DRY_B LIKE T_WC_WIKIPEDIA_PAGE_LANG_SECTION;
ALTER TABLE TMP_DRY_B ADD COLUMN X_COMP mediumtext COMPRESSED DEFAULT NULL, ALGORITHM=INPLACE;
SELECT 'COMPRESSED mediumtext INPLACE on a temporary table: done' AS STEP;

CREATE TEMPORARY TABLE TMP_DRY_C (ID int PRIMARY KEY, A varchar(10)) ENGINE=InnoDB;
ALTER TABLE TMP_DRY_C ADD COLUMN B int DEFAULT NULL, ALGORITHM=INSTANT;
SELECT 'int INSTANT on a small temporary table: done' AS STEP;
