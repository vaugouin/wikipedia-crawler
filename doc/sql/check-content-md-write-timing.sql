-- Read-only, run by the agent after the 1.1.1 restart (2026-10-16): is the crawler waiting on the
-- fetch workers or on its own database writes? TIM_UPDATED is Paris time, to the second, and the
-- window is keyed on the latest section write (see check-content-md-production-minutes.sql).
-- One row per page written in the last 15 minutes: the span of its writes (sections, links,
-- references) and the idle gap before the next page's first write.
CREATE TEMPORARY TABLE tmp_page_span AS
SELECT ID_WIKIDATA, LANG, MIN(T) AS T_START, MAX(T) AS T_END FROM (
  SELECT ID_WIKIDATA, LANG, TIM_UPDATED AS T FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION
  WHERE TIM_UPDATED >= (SELECT MAX(TIM_UPDATED) FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION) - INTERVAL 15 MINUTE
  UNION ALL
  SELECT ID_WIKIDATA, LANG, TIM_UPDATED FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK
  WHERE TIM_UPDATED >= (SELECT MAX(TIM_UPDATED) FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION) - INTERVAL 15 MINUTE
  UNION ALL
  SELECT ID_WIKIDATA, LANG, TIM_UPDATED FROM T_WC_WIKIPEDIA_PAGE_LANG_REFERENCE
  WHERE TIM_UPDATED >= (SELECT MAX(TIM_UPDATED) FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION) - INTERVAL 15 MINUTE
) x GROUP BY ID_WIKIDATA, LANG;

CREATE TEMPORARY TABLE tmp_page_gap AS
SELECT ID_WIKIDATA, LANG, T_START, T_END, TIMESTAMPDIFF(SECOND, T_START, T_END) AS WRITE_S,
  TIMESTAMPDIFF(SECOND, T_END, LEAD(T_START) OVER (ORDER BY T_START, T_END)) AS GAP_S
FROM tmp_page_span;

-- Totals: seconds spent writing pages against seconds with no write at all.
SELECT COUNT(*) AS PAGES, TIMESTAMPDIFF(SECOND, MIN(T_START), MAX(T_END)) AS WINDOW_S,
  SUM(WRITE_S) AS WRITE_S_TOTAL, SUM(GREATEST(GAP_S, 0)) AS GAP_S_TOTAL,
  SUM(WRITE_S >= 2) AS PAGES_WRITE_2S_PLUS, SUM(GAP_S >= 10) AS GAPS_10S_PLUS, MAX(GAP_S) AS MAX_GAP_S
FROM tmp_page_gap;

-- The longest gaps and the longest writes.
SELECT 'gap' AS KIND, ID_WIKIDATA, LANG, T_START, T_END, WRITE_S, GAP_S FROM tmp_page_gap ORDER BY GAP_S DESC LIMIT 10;
SELECT 'write' AS KIND, g.ID_WIKIDATA, g.LANG, g.T_START, g.WRITE_S,
  (SELECT COUNT(*) FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK l WHERE l.ID_WIKIDATA = g.ID_WIKIDATA AND l.LANG = g.LANG) AS LINKS
FROM tmp_page_gap g ORDER BY WRITE_S DESC LIMIT 10;

-- Live links without a Qid in the window, by how the resolution ended.
SELECT RESOLVED_BY, COUNT(*) AS LIVE_WITHOUT_QID, COUNT(DISTINCT ID_WIKIDATA, LANG) AS PAGES
FROM T_WC_WIKIPEDIA_PAGE_LANG_LINK
WHERE TIM_UPDATED >= (SELECT MAX(TIM_UPDATED) FROM T_WC_WIKIPEDIA_PAGE_LANG_SECTION) - INTERVAL 15 MINUTE
  AND IS_REDLINK = 0 AND IS_DATE = 0 AND TARGET_ID_WIKIDATA IS NULL
GROUP BY RESOLVED_BY;
